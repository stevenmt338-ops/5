// دالة لجلب سؤال عشوائي لمستوى محدد
export function getQuestionForLevel(level: number, excludedIds: string[] = []): Question {
  const candidates = QUESTIONS_BANK.filter(q => q.level === level && !excludedIds.includes(q.id));
  if (candidates.length > 0) {
    const randomIndex = Math.floor(Math.random() * candidates.length);
    return candidates[randomIndex];
  }
  // في حال انتهاء الأسئلة في المستوى
  const fallback = QUESTIONS_BANK.filter(q => q.level === level);
  return fallback[Math.floor(Math.random() * fallback.length)] || QUESTIONS_BANK[0];
}
